def run_sql(sql):
    result = subprocess.run(
        ['docker', 'exec', 'pgvector_db', 'psql', '-U', 'jhe', '-d', 'openclaw', '-c', sql],
        capture_output=True, text=True
    )
    if result.returncode != 0:
        print(f"SQL Error: {result.stderr}", file=sys.stderr)
    return result

