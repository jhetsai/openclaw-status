# 匯入電號
print("\n[1/2] 匯入電號資料...")
for account_id, info in METERS.items():
    sql = f"""
    INSERT INTO electricity_meters (account_id, meter_type, address, feeder)
    VALUES ('{account_id}', '{info['t']}', '{info['a']}', '{info['f']}')
    ON CONFLICT (account_id) DO UPDATE SET
        meter_type = EXCLUDED.meter_type,
        address = EXCLUDED.address,
        feeder = EXCLUDED.feeder;
    """
    run_sql(sql)
print(f"  → {len(METERS)} 筆電號匯入完成")

# 匯入計費
print("\n[2/2] 匯入計費資料...")
for bill in BILLS:
    sql = f"""
    INSERT INTO electricity_bills (account_id, period, yyyy, kwh, cost)
    VALUES ('{bill['a']}', '{bill['p']}', {bill['y']}, {bill['k']}, {bill['c']})
    ON CONFLICT DO NOTHING;
    """
    run_sql(sql)
print(f"  → {len(BILLS)} 筆計費資料匯入完成")

# 驗證
print("\n[驗證]")
